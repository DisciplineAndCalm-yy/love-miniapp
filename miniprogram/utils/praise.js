function hash(str) {
  let h = 5381
  const s = String(str || '')
  for (let i = 0; i < s.length; i += 1) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0
  return h
}

// 同一日期 + 天气 恒定取同一句;hourBucket 变化可让同一天多次刷新时略有轮换
function pick(list, seed) {
  if (!list || !list.length) return ''
  return list[hash(seed) % list.length]
}

function dailyPraise(dateKey, cond) {
  const pool = (BY_COND[cond] || []).concat(GENERAL)
  return pick(pool, `${dateKey}|${cond || 'general'}`)
}

// 天气页用：一句主夸 + 一句副夸（不同 seed，避免重复）
function praisePair(dateKey, cond) {
  const main = dailyPraise(dateKey, cond)
  let sub = pick(GENERAL, `${dateKey}|sub|${cond || ''}`)
  if (sub === main) sub = pick(GENERAL, `${dateKey}|sub2|${cond || ''}`)
  return { main, sub }
}

